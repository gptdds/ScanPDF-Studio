from PySide6.QtCore import Signal
from PySide6.QtWidgets import (QCheckBox, QComboBox, QDoubleSpinBox, QFormLayout,
                               QGridLayout, QHBoxLayout, QLabel, QPushButton,
                               QScrollArea, QSpinBox, QVBoxLayout, QWidget)

from scanpdf.app.widgets import Card


def card(title, description=""):
    frame = Card()
    layout = QVBoxLayout(frame)
    layout.setContentsMargins(22, 18, 22, 20)
    layout.setSpacing(10)
    heading = QLabel(title)
    heading.setObjectName("SectionTitle")
    layout.addWidget(heading)
    if description:
        note = QLabel(description)
        note.setObjectName("Subtitle")
        note.setWordWrap(True)
        layout.addWidget(note)
    return frame, layout


class PreferencesPage(QWidget):
    saved = Signal()

    def __init__(self, settings_manager, parent=None):
        super().__init__(parent)
        self.manager = settings_manager
        outer = QVBoxLayout(self)
        outer.setContentsMargins(32, 24, 32, 24)
        title = QLabel("处理设置")
        title.setObjectName("PageTitle")
        subtitle = QLabel("OCR 与排版参数会用于下一次新任务；可随时调整并保存。")
        subtitle.setObjectName("Subtitle")
        outer.addWidget(title)
        outer.addWidget(subtitle)
        outer.addSpacing(16)
        scroll = QScrollArea()
        scroll.setWidgetResizable(True)
        body = QWidget()
        grid = QGridLayout(body)
        grid.setContentsMargins(0, 0, 8, 8)
        grid.setHorizontalSpacing(16)
        grid.setVerticalSpacing(16)
        ocr_frame, ocr_layout = card("OCR 识别", "扫描页先进行方向、倾斜和图像质量处理，再交给 PP-OCRv5。")
        ocr_form = QFormLayout()
        ocr_form.setSpacing(10)
        self.language = QComboBox()
        for label, value in (("简体中文", "ch"), ("繁体中文", "chinese_cht"),
                             ("英文", "en"), ("中英混合", "ch")):
            self.language.addItem(label, value)
        self.quality = QComboBox()
        self.quality.addItem("标准（Mobile，速度快）", "standard")
        self.quality.addItem("高质量（Server，精度优先）", "high")
        self.dpi = QComboBox()
        for dpi in (150, 200, 220, 300, 400):
            self.dpi.addItem(f"{dpi} DPI", dpi)
        self.device = QComboBox()
        self.device.addItem("CPU（通用）", "cpu")
        self.device.addItem("GPU（需 CUDA 推理库）", "gpu")
        ocr_form.addRow("文字语言", self.language)
        ocr_form.addRow("识别质量", self.quality)
        ocr_form.addRow("渲染精度", self.dpi)
        ocr_form.addRow("推理设备", self.device)
        ocr_layout.addLayout(ocr_form)
        checks = QGridLayout()
        checks.setHorizontalSpacing(20)
        self.orientation = QCheckBox("页面方向检测")
        self.deskew = QCheckBox("倾斜校正")
        self.denoise = QCheckBox("去噪")
        self.contrast = QCheckBox("对比度增强")
        self.binarize = QCheckBox("自适应二值化（慎用）")
        for index, checkbox in enumerate((self.orientation, self.deskew, self.denoise,
                                          self.contrast, self.binarize)):
            checks.addWidget(checkbox, index // 2, index % 2)
        ocr_layout.addLayout(checks)
        note = QLabel("简体中文模式会把模型误识别的繁体字形转换为简体；繁体中文模式保留原字形。"
                      "二值化会丢弃纸张纹理，通常不需要启用。"
                      "质量模式使用更大的检测和识别模型，耗时更高。")
        note.setObjectName("Meta")
        note.setWordWrap(True)
        ocr_layout.addWidget(note)
        epub_frame, epub_layout = card("EPUB 3 排版", "正文保持流式，不锁定页面尺寸与字号。")
        epub_form = QFormLayout()
        epub_form.setSpacing(10)
        self.font = QComboBox()
        self.font.addItem("衬线（宋体优先）", "serif")
        self.font.addItem("无衬线（黑体优先）", "sans")
        self.line_height = QDoubleSpinBox()
        self.line_height.setRange(1.2, 2.6)
        self.line_height.setSingleStep(0.1)
        self.line_height.setSuffix(" ×")
        self.reading_mode = QComboBox()
        self.reading_mode.addItem("自动检测（横排/竖排）", "auto")
        self.reading_mode.addItem("横排", "horizontal")
        self.reading_mode.addItem("竖排中文", "vertical")
        self.low_confidence = QDoubleSpinBox()
        self.low_confidence.setRange(0.30, 1.0)
        self.low_confidence.setSingleStep(0.05)
        self.low_confidence.setDecimals(2)
        epub_form.addRow("正文字体", self.font)
        epub_form.addRow("行距", self.line_height)
        epub_form.addRow("阅读方向", self.reading_mode)
        epub_form.addRow("低置信度阈值", self.low_confidence)
        epub_layout.addLayout(epub_form)
        checks2 = QGridLayout()
        checks2.setHorizontalSpacing(20)
        self.chapters = QCheckBox("章节识别")
        self.paragraphs = QCheckBox("段落重建")
        self.merge_pages = QCheckBox("跨页段落合并")
        self.clean_margins = QCheckBox("清理页眉页脚")
        self.clean_numbers = QCheckBox("清理页码")
        self.keep_images = QCheckBox("保留图片与表格")
        self.toc = QCheckBox("生成目录")
        self.indent = QCheckBox("首行缩进")
        for index, checkbox in enumerate((self.chapters, self.paragraphs, self.merge_pages,
                                          self.clean_margins, self.clean_numbers, self.keep_images,
                                          self.toc, self.indent)):
            checks2.addWidget(checkbox, index // 2, index % 2)
        epub_layout.addLayout(checks2)
        app_frame, app_layout = card("应用", "深色主题只改变界面，不改变导出的电子书颜色。")
        app_row = QHBoxLayout()
        self.theme = QComboBox()
        self.theme.addItem("浅色", "light")
        self.theme.addItem("深色", "dark")
        app_row.addWidget(QLabel("界面主题"))
        app_row.addWidget(self.theme, 1)
        app_layout.addLayout(app_row)
        language_note = QLabel("模型文件独立于安装包下载，页面上方会显示真实下载状态与失败重试。")
        language_note.setObjectName("Meta")
        language_note.setWordWrap(True)
        app_layout.addWidget(language_note)
        grid.addWidget(ocr_frame, 0, 0)
        grid.addWidget(epub_frame, 0, 1)
        grid.addWidget(app_frame, 1, 0, 1, 2)
        grid.setColumnStretch(0, 1)
        grid.setColumnStretch(1, 1)
        scroll.setWidget(body)
        outer.addWidget(scroll, 1)
        footer = QHBoxLayout()
        footer.addStretch()
        self.save_button = QPushButton("保存设置")
        self.save_button.setObjectName("Primary")
        self.save_button.clicked.connect(self.save)
        footer.addWidget(self.save_button)
        outer.addLayout(footer)
        self.load()

    def load(self):
        settings = self.manager.settings()
        self._select(self.language, settings.language)
        self._select(self.quality, settings.quality)
        self._select(self.dpi, settings.dpi)
        self._select(self.device, settings.device)
        self._select(self.font, settings.font)
        self._select(self.reading_mode, settings.reading_mode)
        self.orientation.setChecked(settings.orientation)
        self.deskew.setChecked(settings.deskew)
        self.denoise.setChecked(settings.denoise)
        self.contrast.setChecked(settings.contrast)
        self.binarize.setChecked(settings.binarize)
        self.line_height.setValue(settings.line_height)
        self.low_confidence.setValue(settings.low_confidence)
        self.chapters.setChecked(settings.chapters)
        self.paragraphs.setChecked(settings.paragraphs)
        self.merge_pages.setChecked(settings.merge_pages)
        self.clean_margins.setChecked(settings.clean_margins)
        self.clean_numbers.setChecked(settings.clean_page_numbers)
        self.keep_images.setChecked(settings.keep_images)
        self.toc.setChecked(settings.toc)
        self.indent.setChecked(settings.indent)
        self._select(self.theme, self.manager.data.get("theme", "light"))

    def save(self):
        settings = self.manager.settings()
        settings.language = self.language.currentData()
        settings.quality = self.quality.currentData()
        settings.dpi = self.dpi.currentData()
        settings.device = self.device.currentData()
        settings.orientation = self.orientation.isChecked()
        settings.deskew = self.deskew.isChecked()
        settings.denoise = self.denoise.isChecked()
        settings.contrast = self.contrast.isChecked()
        settings.binarize = self.binarize.isChecked()
        settings.font = self.font.currentData()
        settings.line_height = self.line_height.value()
        settings.reading_mode = self.reading_mode.currentData()
        settings.low_confidence = self.low_confidence.value()
        settings.chapters = self.chapters.isChecked()
        settings.paragraphs = self.paragraphs.isChecked()
        settings.merge_pages = self.merge_pages.isChecked()
        settings.clean_margins = self.clean_margins.isChecked()
        settings.clean_page_numbers = self.clean_numbers.isChecked()
        settings.keep_images = self.keep_images.isChecked()
        settings.toc = self.toc.isChecked()
        settings.indent = self.indent.isChecked()
        self.manager.save(settings, theme=self.theme.currentData())
        self.saved.emit()

    @staticmethod
    def _select(combo, value):
        index = combo.findData(value)
        if index >= 0:
            combo.setCurrentIndex(index)

